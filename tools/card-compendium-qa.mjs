import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.TNO_PLAYWRIGHT_DIR || 'playwright');
const base = process.env.TNO_QA_URL || 'http://127.0.0.1:5186';
const output = resolve('docs/art/card-compendium');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { channel: 'msedge' } : {}), args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const receipts = [], errors = [];
try {
  for (const [name, width, height] of [['desktop',1440,900],['mobile',390,844],['landscape',844,390],['small-mobile',320,568]]) {
    const page = await browser.newPage({ viewport: { width, height }, reducedMotion: 'reduce' });
    page.on('pageerror', error => errors.push(`${name}: ${error.message}`));
    await page.goto(`${base}/tools/card-compendium-review.html`, { waitUntil: 'networkidle' });
    await page.locator('#card-compendium-overlay').waitFor({ state: 'visible' });
    await page.evaluate(() => document.fonts.ready);
    const bounds = await page.locator('.cc-panel').boundingBox();
    assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= width + 1 && bounds.y + bounds.height <= height + 1, `${name}: panel contained`);
    assert.match(await page.locator('#cc-progress-count').innerText(), /8.*65/);
    assert.equal(await page.locator('[data-cc-card]').count(), 65);
    const artCoverage = await page.evaluate(async () => {
      const { CARD_ILLUSTRATIONS } = await import('/src/character/data/card-illustrations.js');
      const { MONSTER_MODELS } = await import('/src/combat/MonsterModels.js');
      return { art: Object.keys(CARD_ILLUSTRATIONS).sort(), models: Object.keys(MONSTER_MODELS).sort() };
    });
    assert.equal(artCoverage.art.length, 31);
    assert.deepEqual(artCoverage.art, artCoverage.models, `${name}: only designed monster models`);
    await page.locator('#cc-search').fill('ชาละวัน');
    assert.equal(await page.locator('[data-cc-card]').count(), 1);
    await page.locator('[data-cc-card="card_chalawan"]').click();
    await page.locator('.cc-special').waitFor({ state: 'visible' });
    assert.match(await page.locator('.cc-special').innerText(), /15%.*40%/);
    const portrait = page.locator('.cc-detail-head .cc-image');
    await portrait.evaluate(img => img.decode());
    assert.deepEqual(await portrait.evaluate(img => [img.naturalWidth, img.naturalHeight]), [384, 480]);
    const thumb = page.locator('[data-cc-card="card_chalawan"] .cc-image');
    await thumb.evaluate(img => img.decode());
    assert.deepEqual(await thumb.evaluate(img => [img.naturalWidth, img.naturalHeight]), [96, 120]);
    await page.screenshot({ path: resolve(output, `${name}-card.png`) });
    if (width < 701 && height > 500) await page.locator('#cc-view-catalog').click();
    await page.locator('#cc-search').fill('');
    await page.locator('.cc-filter-drawer summary').click();
    await page.locator('#cc-kind').selectOption('boss');
    assert.equal(await page.locator('[data-cc-card]').count(), 13);
    await page.locator('#cc-kind').selectOption('');
    await page.locator('#cc-map').selectOption('unavailable');
    assert.equal(await page.locator('[data-cc-card]').count(), 2);
    await page.locator('[data-cc-reset]').click();
    await page.evaluate(() => window.cardReview.character.addItem('card_leech'));
    assert.match(await page.locator('#cc-progress-count').innerText(), /9.*65/);
    await page.locator('#cc-tab-guide').click();
    assert.equal(await page.locator('#cc-guide').isVisible(), true);
    await page.screenshot({ path: resolve(output, `${name}-guide.png`) });
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#card-compendium-overlay').isVisible(), false);
    await page.locator('#review-cards').click();
    await page.locator('[data-cc-close]').click();
    assert.equal(await page.evaluate(() => document.activeElement.id), 'review-cards');
    await page.locator('#review-cards').click();
    const trap = await page.evaluate(() => {
      const panel = document.querySelector('#card-compendium-overlay');
      const focusable = [...panel.querySelectorAll('button,input,select,summary,[tabindex]')].filter(el => !el.disabled && el.tabIndex >= 0 && el.getClientRects().length);
      focusable.at(-1).focus(); return focusable[0].outerHTML;
    });
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.outerHTML), trap, `${name}: Tab wraps`);
    receipts.push({ name, viewport: { width, height }, panel: bounds, catalog: 65, designedModelIllustrations: 31, portrait: [384,480], thumbnail: [96,120], bossesAndGuardians: 13, unavailable: 2, reactiveCollection: true, focusReturn: true, tabContainment: true });
    await page.close();
  }
  const game = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  game.on('pageerror', error => errors.push(`game: ${error.message}`));
  // Local disposable guest; keep QA away from the user's running multiplayer server.
  await game.route('**/api/**', route => route.fulfill({ status: 200, contentType: 'application/json', body: '{"accounts":false}' }));
  await game.routeWebSocket('**/ws', socket => socket.close());
  await game.addInitScript(() => localStorage.setItem('tno.view.v1', JSON.stringify({ quality: 'low', particles: false, monsters: 'pixel' })));
  await game.goto(base, { waitUntil: 'domcontentloaded' });
  await game.locator('.acc-guest').click();
  await game.locator('.acc-empty').first().click();
  await game.locator('.g-name input').fill('ผู้ทดสอบสมุด');
  await game.locator('.g-start').click();
  await game.locator('#loading').waitFor({ state: 'hidden', timeout: 60000 });
  await game.locator('#menu-btn').click();
  await game.locator('[data-act="cards"]').click();
  await game.locator('#card-compendium-overlay').waitFor({ state: 'visible' });
  assert.equal(await game.locator('[data-cc-card]').count(), 65);
  assert.equal(await game.locator('#settings').isVisible(), false);
  const zoom = await game.locator('#zoom').inputValue();
  await game.locator('[data-cc-close]').focus();
  await game.keyboard.press('Equal');
  assert.equal(await game.locator('#zoom').inputValue(), zoom, 'camera shortcut is gated under journal');
  await game.locator('#cc-search').fill('ชาละวัน');
  await game.locator('[data-cc-card="card_chalawan"]').click();
  await game.screenshot({ path: resolve(output, 'game-desktop-card.png') });
  await game.keyboard.press('Escape');
  assert.equal(await game.locator('#card-compendium-overlay').isVisible(), false);
  assert.equal(await game.evaluate(() => document.activeElement.id), 'menu-btn');
  await game.locator('#menu-btn').click();
  await game.locator('[data-act="guide"]').click();
  await game.locator('#cc-guide').waitFor({ state: 'visible' });
  await game.locator('#cc-guide [data-cc-action="bag"]').first().click();
  assert.equal(await game.locator('#card-compendium-overlay').isVisible(), false);
  assert.equal(await game.locator('.g-bag').isVisible(), true);
  receipts.push({ name: 'actual-game-desktop', disposableOfflineGuest: true, menuCards: true, menuGuide: true, guideBagShortcut: true, cameraGated: true, menuFocusReturn: true });
  await game.keyboard.press('Escape');
  await game.setViewportSize({ width: 390, height: 844 });
  await game.locator('#menu-btn').click();
  const menu = await game.locator('#menu-grid').boundingBox();
  assert.ok(menu.x >= 0 && menu.y >= 0 && menu.x + menu.width <= 391 && menu.y + menu.height <= 845, 'mobile game menu stays inside screen');
  await game.locator('[data-act="cards"]').click();
  await game.locator('#cc-search').fill('นาคราช');
  await game.locator('[data-cc-card="card_sunken_city_3"]').click();
  await game.locator('.cc-detail-head .cc-image').evaluate(img => img.decode());
  await game.screenshot({ path: resolve(output, 'game-mobile-card.png') });
  await game.keyboard.press('Escape');
  assert.equal(await game.evaluate(() => document.activeElement.id), 'menu-btn');
  receipts.push({ name: 'actual-game-mobile', viewport: { width: 390, height: 844 }, menuContained: true, cardDetail: true, menuFocusReturn: true });
  await game.close();
  assert.deepEqual(errors, []);
  await writeFile(resolve(output, 'browser-qa.json'), JSON.stringify({ fixture: 'tools/card-compendium-review.html', receipts, errors }, null, 2));
  console.log(JSON.stringify({ passed: receipts.length, screenshots: 10, errors }, null, 2));
} finally { await browser.close(); }
